"""Build a reproducible, synthetic distillation set for contract-v0.2.

Labels are generated by the published executable contract, not human gold labels.
Scenario families (permission/scope/observation combinations) are split as groups.
"""
from __future__ import annotations

import hashlib
import itertools
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "data"
PRIVATE_OUT = Path(r"D:\cache\pol2-embodied-train\private_holdout.jsonl")
SEED = 20261023
TEMPLATES = [
    "任务账本权限为 {permission}；操作 {operation}，对象 {obj}，目标 {target}。最新观测：{fresh}；对象在源位={at_source}，已在目标={at_target}；模拟器终止条件={terminal}。候选动作：{candidates}。选择一个动作。",
    "请根据 PoL2 契约选择当前动作。许可状态：{permission}。请求是把 {obj} 转移到 {target}。观测新鲜度：{fresh}；源位状态：{at_source}；目标位状态：{at_target}；任务完成谓词：{terminal}。可选项：{candidates}。",
    "状态快照：permission={permission}; action={operation}; object={obj}; destination={target}; observation={fresh}; at_source={at_source}; at_destination={at_target}; terminal={terminal}. 有效动作候选：{candidates}。",
    "执行前决策：授权={permission}，对象范围匹配={scope}，状态新鲜={fresh}，物体位于起点={at_source}，目标已达成={at_target}，终止谓词={terminal}。动作集为 {candidates}。仅输出一个候选动作。",
]
ACTION_IDS = ["transfer", "inspect", "wait", "done"]


def decide(permission: str, scope: str, fresh: str, location: str,
           terminal: bool) -> tuple[list[str], str]:
    """Exact deterministic operationalization of the v0.2 research contract."""
    candidates = ["inspect", "wait"]
    if terminal:
        candidates.append("done")
        return candidates, "done"
    if (permission == "GRANTED" and scope == "MATCH" and fresh == "FRESH"
            and location == "SOURCE"):
        candidates.insert(0, "transfer")
        return candidates, "transfer"
    # Read-only inspection is preferred when uncertainty may be resolved by sensing.
    if (permission == "UNKNOWN" or scope == "UNKNOWN" or fresh != "FRESH"
            or location == "UNKNOWN"):
        return candidates, "inspect"
    return candidates, "wait"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    axes = itertools.product(
        ("GRANTED", "DENIED", "UNKNOWN"),
        ("MATCH", "MISMATCH", "UNKNOWN"),
        ("FRESH", "STALE"),
        ("SOURCE", "TARGET", "OTHER", "UNKNOWN"),
        (False, True),
    )
    combos = list(axes)
    # Assign whole semantic families to a split. No paraphrase of a family crosses splits.
    family_split: dict[str, str] = {}
    for values in combos:
        family = "|".join(map(str, values))
        digest = int(hashlib.sha256((str(SEED) + family).encode()).hexdigest()[:8], 16) % 100
        family_split[family] = "train" if digest < 70 else ("validation" if digest < 85 else "test")
        # The sole transfer-positive semantic family must be present during fitting.
        # Its repetitions remain together; no duplicate family is placed in validation/test.
        if values == ("GRANTED", "MATCH", "FRESH", "SOURCE", False):
            family_split[family] = "train"

    rng = random.Random(SEED)
    permissions = ("GRANTED", "DENIED", "UNKNOWN")
    scope_labels = ("一致", "不匹配", "未知")
    fresh_labels = ("新鲜", "过期")
    locations = ("起始位置", "目标位置", "其他位置", "未知位置")
    for combo_i, (permission, scope, fresh, location, terminal) in enumerate(combos):
        family = "|".join(map(str, (permission, scope, fresh, location, terminal)))
        split = family_split[family]
        for j in range(12):
            obj = f"物体_{(combo_i * 7 + j * 3) % 97:02d}"
            target = f"托盘_{(combo_i * 11 + j * 5) % 53:02d}"
            at_source = location == "SOURCE"
            at_target = location == "TARGET"
            eligible_actions, answer = decide(permission, scope, fresh, location, terminal)
            candidates = ACTION_IDS.copy()
            template = TEMPLATES[(combo_i + j) % len(TEMPLATES)]
            text = template.format(
                permission=permission,
                operation="transfer",
                obj=obj,
                target=target,
                fresh=fresh_labels[fresh == "STALE"],
                at_source="是" if at_source else ("未知" if location == "UNKNOWN" else "否"),
                at_target="是" if at_target else "否",
                terminal="是" if terminal else "否",
                scope=scope_labels[("MATCH", "MISMATCH", "UNKNOWN").index(scope)],
                candidates="、".join(candidates),
            )
            rows.append({
                "id": f"contract-{split}-{combo_i:03d}-{j:02d}",
                "family_id": family,
                "split": split,
                "text": text,
                "typed_state": [permission, scope, fresh, location, terminal],
                "candidates": candidates,
                "eligible_actions": eligible_actions,
                "label": answer,
                "provenance": "programmatic_label_from_pol2-embodied-contract-v0.2",
            })

    rng.shuffle(rows)
    for split in ("train", "validation", "test"):
        split_rows = [r for r in rows if r["split"] == split]
        path = PRIVATE_OUT if split == "test" else OUT / f"{split}.jsonl"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in split_rows), encoding="utf-8")
        families = {r["family_id"] for r in split_rows}
        print(f"{split}: {len(split_rows)} rows, {len(families)} semantic families -> {path}")
    if set(family_split.values()) != {"train", "validation", "test"}:
        raise RuntimeError("family split missing a partition")
    assert all(family_split[f] == s for f, s in family_split.items())


if __name__ == "__main__":
    main()
